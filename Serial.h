//串口通信中介者类
class HardwareComMediator
{
protected:
	virtual bool PackCmdWrite(unsigned char* strOutMsg, float value, int* length, PowerQueryType powerquerytype) = 0;
	virtual bool PackCmdRead(unsigned char* strOutMsg, int* length, PowerQueryType powerquerytype) = 0;
	virtual bool PackSCPICmd(unsigned char* strInMsg, unsigned char* strOutMsg, int* length) = 0;
	virtual float ReadSetVLOT() = 0;
	virtual signed long MBMasterSnd(unsigned char Addr, unsigned char RegCode, signed long RegStart, signed long RegNum, void* src, signed long srclen, unsigned char* dst) = 0;
public:	
	virtual bool Set_Dev_Vol_Curr(CSerial* serial, float voltage, float current) = 0;
	virtual bool Get_Dev_Vol_Curr(CSerial* serial, float* voltage, float* current) = 0;

	virtual bool SetSCPICommand(CSerial* serial, unsigned char* pData) = 0;
	virtual bool GetSCPICommand(CSerial* serial, unsigned char* pData) = 0;

	virtual bool WriteDO(CSerial* serial, signed long ioindex, bool onoff) = 0;
};

